"""Generate the platinum RTD table of the OHM temperature view (IMP-25): firmware/src/mtmp/rtd_table.s.

    python -I firmware/tools/gen_rtd_table.py

The table holds W(T) = R(T) / R0 in parts per million (ppm, rounded to the nearest integer) at T = 5 k - 200 degC,
k = 0..210 (-200..850 degC), from the Callendar-Van Dusen equation of IEC 60751:2008 (industrial platinum resistance
thermometers, alpha = 0.00385):
    -200 <= T < 0 degC:   W = 1 + A T + B T^2 + C (T - 100) T^3
    0 <= T <= 850 degC:   W = 1 + A T + B T^2
    A = 3.9083e-3, B = -5.775e-7, C = -4.183e-12
The firmware (ui/rtd.s) converts a resistance to a temperature by linear interpolation between two entries.

Checks made before writing (the generator stops when one fails):
  - the equation gives the IEC 60751 Pt100 table values -200 degC 18.52, -100 degC 60.26, 0 degC 100.00,
    100 degC 138.51, 850 degC 390.48 ohm (to 0.01 ohm);
  - the table rises strictly;
  - the firmware arithmetic (integer interpolation, half away from zero, of the ppm table) is replayed for every
    resistance step the meter resolves in the Pt100 range 500.00 ohm (0.01 ohm) from W(-200) to W(850), and compared
    with the exact inverse of the equation (bisection); the largest error is printed and must stay below 0.01 degC (the result is in 0.01 degC, so 0.005 of it is the final rounding).
"""
import os
import sys
from fractions import Fraction as F

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(ROOT, 'firmware', 'src', 'mtmp', 'rtd_table.s')

A = F(39083, 10 ** 7)
B = F(-5775, 10 ** 10)
C = F(-4183, 10 ** 15)
T_LO, T_HI, STEP = -200, 850, 5


def w(t):
    """W(T) = R(T) / R0, exact (t a Fraction or int, degC)."""
    t = F(t)
    v = 1 + A * t + B * t * t
    if t < 0:
        v += C * (t - 100) * t ** 3
    return v


def t_of_w(x):
    """Exact inverse of w by bisection (x a Fraction inside W(-200)..W(850)), as a float degC."""
    lo, hi = F(T_LO), F(T_HI)
    for _ in range(80):
        mid = (lo + hi) / 2
        if w(mid) < x:
            lo = mid
        else:
            hi = mid
    return float((lo + hi) / 2)


def rnd(q):
    """Round a Fraction half away from zero."""
    n = abs(q.numerator) * 2 + q.denominator
    v = n // (2 * q.denominator)
    return v if q >= 0 else -v


def firmware_t001(ppm, tab):
    """Replay of ui_rtd_draw: temperature in 0.01 degC from W in ppm (None outside the table)."""
    if ppm < tab[0] or ppm > tab[-1]:
        return None
    k = 0
    while k < len(tab) - 2 and ppm > tab[k + 1]:
        k += 1
    d = tab[k + 1] - tab[k]
    return 500 * k - 20000 + ((ppm - tab[k]) * 500 + d // 2) // d


def main():
    for t, r in ((-200, '18.52'), (-100, '60.26'), (0, '100.00'), (100, '138.51'), (850, '390.48')):
        got = rnd(w(t) * 100 * 100)                 # Pt100 in 0.01 ohm
        if got != int(r.replace('.', '')):
            raise SystemExit('IEC 60751 check failed at %d degC: %d x 0.01 ohm, table %s ohm' % (t, got, r))
    tab = [rnd(w(t) * 10 ** 6) for t in range(T_LO, T_HI + 1, STEP)]
    if any(b <= a for a, b in zip(tab, tab[1:])):
        raise SystemExit('table does not rise strictly')
    worst, worst_at = 0.0, None
    for r001 in range(-(-tab[0] // 100), tab[-1] // 100 + 1):   # Pt100 r1: 0.01 ohm = 100 ppm of 100 ohm
        ppm = r001 * 100
        t = firmware_t001(ppm, tab)
        err = abs(t / 100.0 - t_of_w(F(ppm, 10 ** 6)))
        if err > worst:
            worst, worst_at = err, r001
    if worst >= 0.01:
        raise SystemExit('interpolation error %.4f degC at %.2f ohm' % (worst, worst_at / 100.0))
    lines = [
        '@ =============================================================================',
        '@ rtd_table.s - MTMP: platinum RTD table of the OHM temperature view (production image only, DESIGN.md 10 IMP-25,',
        '@ FEATURES.md 2.15)',
        '@',
        '@ Generated by firmware/tools/gen_rtd_table.py from the Callendar-Van Dusen equation of IEC 60751:2008',
        '@ (A = 3.9083e-3, B = -5.775e-7, C = -4.183e-12).  Do not edit by hand.',
        '@ W(T) = R(T) / R0 in ppm at T = 5 k - 200 degC, k = 0..210 (-200..850 degC); entry 40 = 0 degC = 1000000.',
        '@ The same table serves Pt100 (R0 100 ohm) and Pt1000 (R0 1000 ohm).  Largest error of the conversion of',
        '@ ui/rtd.s (interpolation, result in 0.01 degC) against the exact inverse, every 0.01 ohm of a Pt100: %.4f degC (at %.2f ohm).' % (worst, worst_at / 100.0),
        '@ =============================================================================',
        '',
        '    .syntax unified',
        '    .include "config.inc"',
        '',
        '    .if LOOP_V205 == 0',
        '',
        '    .section .rodata.mtmp.rtd, "a", %progbits',
        '    .balign 4',
        '    .global mtmp_rtd_tab',
        'mtmp_rtd_tab:',
    ]
    for i in range(0, len(tab), 8):
        row = tab[i:i + 8]
        t0 = T_LO + STEP * i
        lines.append('    .word %s   @ %d..%d degC' % (', '.join(str(v) for v in row), t0, t0 + STEP * (len(row) - 1)))
    lines += [
        '    .size mtmp_rtd_tab, . - mtmp_rtd_tab',
        '    .global mtmp_rtd_end',
        'mtmp_rtd_end:                           @ end of the table (the last entry is at mtmp_rtd_end - 4)',
        '',
        '    .endif',
        '',
    ]
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    print('%s: %d entries, W(-200) = %d ppm, W(850) = %d ppm, interpolation error <= %.4f degC'
          % (os.path.relpath(OUT, ROOT), len(tab), tab[0], tab[-1], worst))


if __name__ == '__main__':
    main()
